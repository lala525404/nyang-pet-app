const pad2 = (n: number) => String(n).padStart(2, '0');

// 그 날(Date)의 공휴일 이름. 내장 범위(2026~2027) 밖이거나 평일이면 null
export const holidayName = (d: Date): string | null => HOLIDAYS[`${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`] ?? null;

